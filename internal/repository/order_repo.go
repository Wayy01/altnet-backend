// UpdateOrder updates order details (not status or items)
func (r *OrderRepository) UpdateOrder(ctx context.Context, id uuid.UUID, input *models.UpdateOrderInput) (*models.Order, error) {
	// Build dynamic update query
	var setClauses []string
	var args []interface{}
	argNum := 1

	if input.FullName != nil {
		setClauses = append(setClauses, fmt.Sprintf("full_name = $%d", argNum))
		args = append(args, strings.TrimSpace(*input.FullName))
		argNum++
	}
	if input.PhoneNumber != nil {
		setClauses = append(setClauses, fmt.Sprintf("phone_number = $%d", argNum))
		args = append(args, strings.TrimSpace(*input.PhoneNumber))
		argNum++
	}
	if input.Email != nil {
		setClauses = append(setClauses, fmt.Sprintf("email = $%d", argNum))
		args = append(args, input.Email)
		argNum++
	}
	if input.DeliveryType != nil {
		setClauses = append(setClauses, fmt.Sprintf("delivery_type = $%d", argNum))
		args = append(args, *input.DeliveryType)
		argNum++
	}
	if input.DeliveryAddress != nil {
		setClauses = append(setClauses, fmt.Sprintf("delivery_address = $%d", argNum))
		args = append(args, input.DeliveryAddress)
		argNum++
	}
	if input.StoreID != nil {
		setClauses = append(setClauses, fmt.Sprintf("store_id = $%d", argNum))
		args = append(args, input.StoreID)
		argNum++
	}
	if input.PaymentMethod != nil {
		setClauses = append(setClauses, fmt.Sprintf("payment_method = $%d", argNum))
		args = append(args, *input.PaymentMethod)
		argNum++
	}
	if input.Notes != nil {
		setClauses = append(setClauses, fmt.Sprintf("notes = $%d", argNum))
		args = append(args, input.Notes)
		argNum++
	}

	if len(setClauses) == 0 {
		return r.getOrderByID(ctx, id)
	}

	setClauses = append(setClauses, "updated_at = NOW()")

	query := fmt.Sprintf(`
		UPDATE orders
		SET %s
		WHERE id = $%d
		RETURNING id, order_number, full_name, phone_number, email, delivery_type, delivery_address,
		          store_id, payment_method, total_amount, currency, status, notes,
		          user_id, user_name, user_pfp, created_at, updated_at
	`, strings.Join(setClauses, ", "), argNum)
	args = append(args, id)

	order := &models.Order{}
	err := r.pool.QueryRow(ctx, query, args...).Scan(
		&order.ID,
		&order.OrderNumber,
		&order.FullName,
		&order.PhoneNumber,
		&order.Email,
		&order.DeliveryType,
		&order.DeliveryAddress,
		&order.StoreID,
		&order.PaymentMethod,
		&order.TotalAmount,
		&order.Currency,
		&order.Status,
		&order.Notes,
		&order.UserID,
		&order.UserName,
		&order.UserPfp,
		&order.CreatedAt,
		&order.UpdatedAt,
	)
	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			return nil, ErrOrderNotFound
		}
		return nil, fmt.Errorf("update order: %w", err)
	}

	return order, nil
}

// UpdateOrderStatus updates the order status with validation
// Uses row-level locking to prevent race conditions when multiple requests
// attempt to update the same order's status concurrently
func (r *OrderRepository) UpdateOrderStatus(ctx context.Context, id uuid.UUID, newStatus string) (*models.Order, error) {
	// Validate new status
	if !models.IsValidOrderStatus(newStatus) {
		return nil, fmt.Errorf("invalid status: %s", newStatus)
	}

	// Start transaction
	tx, err := r.pool.Begin(ctx)
	if err != nil {
		return nil, fmt.Errorf("begin transaction: %w", err)
	}
	defer tx.Rollback(ctx)

	// Lock the row and get current status
	var currentStatus string
	err = tx.QueryRow(ctx, `SELECT status FROM orders WHERE id = $1 FOR UPDATE`, id).Scan(&currentStatus)
	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			return nil, ErrOrderNotFound
		}
		return nil, fmt.Errorf("get current status: %w", err)
	}

	// Validate status transition
	if !models.CanTransitionTo(currentStatus, newStatus) {
		return nil, fmt.Errorf("%w: cannot transition from %s to %s", ErrInvalidStatusTransition, currentStatus, newStatus)
	}

	// Update status within transaction
	query := `
		UPDATE orders
		SET status = $1, updated_at = NOW()
		WHERE id = $2
		RETURNING id, order_number, full_name, phone_number, email, delivery_type, delivery_address,
		          store_id, payment_method, total_amount, currency, status, notes,
		          user_id, user_name, user_pfp, created_at, updated_at
	`

	order := &models.Order{}
	err = tx.QueryRow(ctx, query, newStatus, id).Scan(
		&order.ID,
		&order.OrderNumber,
		&order.FullName,
		&order.PhoneNumber,
		&order.Email,
		&order.DeliveryType,
		&order.DeliveryAddress,
		&order.StoreID,
		&order.PaymentMethod,
		&order.TotalAmount,
		&order.Currency,
		&order.Status,
		&order.Notes,
		&order.UserID,
		&order.UserName,
		&order.UserPfp,
		&order.CreatedAt,
		&order.UpdatedAt,
	)
	if err != nil {
		return nil, fmt.Errorf("update order status: %w", err)
	}

	// Commit transaction
	if err := tx.Commit(ctx); err != nil {
		return nil, fmt.Errorf("commit transaction: %w", err)
	}

	return order, nil
}

// DeleteOrder deletes an order and its items (CASCADE)
func (r *OrderRepository) DeleteOrder(ctx context.Context, id uuid.UUID) error {
	query := `DELETE FROM orders WHERE id = $1`

	cmdTag, err := r.pool.Exec(ctx, query, id)
	if err != nil {
		return fmt.Errorf("delete order: %w", err)
	}

	if cmdTag.RowsAffected() == 0 {
		return ErrOrderNotFound
	}

	return nil
}

// ListOrders returns orders with filters and pagination
func (r *OrderRepository) ListOrders(ctx context.Context, filters *models.OrderFilters, limit, offset int) ([]*models.Order, error) {
	query := `
		SELECT
			o.id, o.order_number, o.full_name, o.phone_number, o.email,
			o.delivery_type, o.delivery_address, o.store_id, o.payment_method,
			o.total_amount, o.currency, o.status, o.notes,
			o.user_id, o.user_name, o.user_pfp, o.created_at, o.updated_at,
			s.name as store_name
		FROM orders o
		LEFT JOIN stores s ON s.id = o.store_id
	`

	var conditions []string
	var args []interface{}
	argNum := 1

	if filters != nil {
		if filters.Search != "" {
			conditions = append(conditions, fmt.Sprintf("(o.order_number ILIKE $%d OR o.full_name ILIKE $%d OR o.phone_number ILIKE $%d)", argNum, argNum, argNum))
			args = append(args, "%"+filters.Search+"%")
			argNum++
		}
		if filters.Status != nil {
			conditions = append(conditions, fmt.Sprintf("o.status = $%d", argNum))
			args = append(args, *filters.Status)
			argNum++
		}
		if filters.PaymentMethod != nil {
			conditions = append(conditions, fmt.Sprintf("o.payment_method = $%d", argNum))
			args = append(args, *filters.PaymentMethod)
			argNum++
		}
		if filters.DeliveryType != nil {
			conditions = append(conditions, fmt.Sprintf("o.delivery_type = $%d", argNum))
			args = append(args, *filters.DeliveryType)
			argNum++
		}
		if filters.StoreID != nil {
			conditions = append(conditions, fmt.Sprintf("o.store_id = $%d", argNum))
			args = append(args, *filters.StoreID)
			argNum++
		}
		if filters.DateFrom != nil {
			conditions = append(conditions, fmt.Sprintf("o.created_at >= $%d", argNum))
			args = append(args, *filters.DateFrom)
			argNum++
		}
		if filters.DateTo != nil {
			conditions = append(conditions, fmt.Sprintf("o.created_at <= $%d", argNum))
			args = append(args, *filters.DateTo)
			argNum++
		}
		if filters.UserID != nil {
			conditions = append(conditions, fmt.Sprintf("o.user_id = $%d", argNum))
			args = append(args, *filters.UserID)
			argNum++
		}
	}

	if len(conditions) > 0 {
		query += " WHERE " + strings.Join(conditions, " AND ")
	}

	query += " ORDER BY o.created_at DESC"

	// Add pagination
	query += fmt.Sprintf(" LIMIT $%d OFFSET $%d", argNum, argNum+1)
	args = append(args, limit, offset)

	rows, err := r.pool.Query(ctx, query, args...)
	if err != nil {
		return nil, fmt.Errorf("query orders: %w", err)
	}
	defer rows.Close()

	var orders []*models.Order
	for rows.Next() {
		order := &models.Order{}
		if err := rows.Scan(
			&order.ID,
			&order.OrderNumber,
			&order.FullName,
			&order.PhoneNumber,
			&order.Email,
			&order.DeliveryType,
			&order.DeliveryAddress,
			&order.StoreID,
			&order.PaymentMethod,
			&order.TotalAmount,
			&order.Currency,
			&order.Status,
			&order.Notes,
			&order.UserID,
			&order.UserName,
			&order.UserPfp,
			&order.CreatedAt,
			&order.UpdatedAt,
			&order.StoreName,
		); err != nil {
			return nil, fmt.Errorf("scan order: %w", err)
		}
		orders = append(orders, order)
	}

	if err := rows.Err(); err != nil {
		return nil, fmt.Errorf("iterate orders: %w", err)
	}

	return orders, nil
}

