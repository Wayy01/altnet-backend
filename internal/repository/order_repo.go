// validateCreateOrderInput validates order creation input
func (r *OrderRepository) validateCreateOrderInput(input *models.CreateOrderInput) error {
	// Validate required fields
	if strings.TrimSpace(input.FullName) == "" {
		return fmt.Errorf("%w: full_name is required", ErrInvalidOrderInput)
	}
	if strings.TrimSpace(input.PhoneNumber) == "" {
		return fmt.Errorf("%w: phone_number is required", ErrInvalidOrderInput)
	}

	// Validate email format if provided
	if input.Email != nil && *input.Email != "" {
		if !emailRegex.MatchString(*input.Email) {
			return fmt.Errorf("%w: invalid email format", ErrInvalidOrderInput)
		}
	}

	// Validate phone number format
	phone := strings.ReplaceAll(input.PhoneNumber, " ", "")
	if !phoneRegex.MatchString(phone) {
		return fmt.Errorf("%w: invalid phone number format", ErrInvalidOrderInput)
	}

	// Validate delivery type
	if !models.IsValidDeliveryType(input.DeliveryType) {
		return fmt.Errorf("%w: invalid delivery_type", ErrInvalidOrderInput)
	}

	// Validate delivery-specific fields
	if input.DeliveryType == models.DeliveryTypePickup && input.StoreID == nil {
		return ErrStoreRequiredForPickup
	}
	if input.DeliveryType == models.DeliveryTypeDelivery && input.DeliveryAddress == nil {
		return ErrAddressRequiredForDelivery
	}

	// Validate payment method
	if !models.IsValidPaymentMethod(input.PaymentMethod) {
		return fmt.Errorf("%w: invalid payment_method", ErrInvalidOrderInput)
	}

	// Validate items
	if len(input.Items) == 0 {
		return fmt.Errorf("%w: at least one item is required", ErrInvalidOrderInput)
	}

	// Validate maximum items per order
	if len(input.Items) > 100 {
		return fmt.Errorf("%w: maximum 100 items per order", ErrInvalidOrderInput)
	}

	for i, item := range input.Items {
		if item.Quantity <= 0 {
			return fmt.Errorf("%w: item %d quantity must be greater than 0", ErrInvalidOrderInput, i)
		}
	}

	return nil
}

